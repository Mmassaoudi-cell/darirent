export type Locale = "fr" | "ar" | "en";

export function readLocale(value: string | string[] | undefined): Locale {
  const locale = Array.isArray(value) ? value[0] : value;
  return locale === "ar" || locale === "en" ? locale : "fr";
}

export function localizedScoreLabel(locale: Locale, score: number) {
  const labels = {
    fr: ["Prudence élevée", "Opportunité faible", "À examiner attentivement", "À considérer", "Belle opportunité", "Correspondance exceptionnelle"],
    ar: ["حذر شديد", "فرصة ضعيفة", "تحتاج مراجعة دقيقة", "تستحق النظر", "فرصة جيدة", "تطابق استثنائي"],
    en: ["High caution", "Weak opportunity", "Review carefully", "Worth considering", "Strong opportunity", "Exceptional match"],
  }[locale];
  return score >= 90 ? labels[5] : score >= 80 ? labels[4] : score >= 70 ? labels[3] : score >= 60 ? labels[2] : score >= 40 ? labels[1] : labels[0];
}

